"""Pre-gold round 2: extended C1 grids and one stage-specific rule, on the tuning images only.

Candidates come from `configs/experiments/phase3_round2.yaml` (written before any
of their results was looked at). Each candidate gives every disease group a list
of options (threshold x halo on/off); the option is chosen by tuning MAE on input
B, and **chosen again inside every leave-one-out fold**, so the leave-one-out MAE
covers every choice the candidate makes.

**Change rule (Adrija):** the frozen method changes only if a candidate's
leave-one-out MAE is more than 3.64 points below that of the frozen method
(candidate `v1`). Only tuning images are read; nothing here can load a gold image.

Usage:
    python -m src.severity.pregold_round2 --config configs/config.yaml \
        --experiment configs/experiments/phase3_round2.yaml [--debug]
"""

import argparse
import json
import shutil
from datetime import date
from pathlib import Path

import numpy as np
import yaml

from src.severity import severity_pipeline as sp
from src.severity import tune_refinement as tr
from src.severity.leaf_mask import tuning_rows
from src.severity.metrics import bootstrap_ci
from src.severity.refinement import GROUPS
from src.utils.config import load_config
from src.utils.experiment import create_experiment_dir
from src.utils.git import get_git_commit_hash

TABLE = Path("report/tables/pregold_round2.md")
Option = tuple[float, bool]  # (threshold, halo)


def options(candidate: dict) -> dict[str, list[Option]]:
    """Per group, the options in tie-break order: halo values in listed order, then thresholds in listed order."""
    return {g: [(t, bool(h)) for h in candidate[g]["halo"] for t in candidate[g]["thresholds"]] for g in GROUPS}


def make_records(items: list[dict], all_options: dict[str, list[Option]]) -> list[dict]:
    """Per image: rating, group, and C1 severity on each input for every option of its group."""
    return [{"name": i["name"], "disease": i["disease"], "group": i["group"], "rating": i["rating"],
             "c1": {key: {o: sp.c1_severity(i, key, o[0], o[1]) for o in all_options[i["group"]]} for key in sp.INPUTS}}
            for i in items]


def _summary(pred: list[float], ratings: list[float]) -> dict:
    m, lo, hi = bootstrap_ci(np.abs(np.asarray(pred) - np.asarray(ratings)).tolist())
    return {"mae": m, "ci_low": lo, "ci_high": hi, "mean_signed_error": float(np.mean(np.asarray(pred) - np.asarray(ratings)))}


def evaluate_candidate(records: list[dict], grid: dict[str, list[Option]], key: str) -> dict:
    """Chosen option per group, in-sample and leave-one-out MAE, per-option MAE per group, per-image predictions."""
    ratings = [r["rating"] for r in records]
    chosen = tr.choose_thresholds(records, grid, key)
    in_sample, loo = tr.c1_predictions(records, chosen, key), tr.leave_one_out(records, grid, key)
    return {
        "chosen": {g: (None if o is None else {"threshold": o[0], "halo": o[1]}) for g, o in chosen.items()},
        "in_sample": _summary(in_sample, ratings), "leave_one_out": _summary(loo, ratings),
        "option_mae": {g: [{"threshold": o[0], "halo": o[1],
                            "mae": sp.mae([r["c1"][key][o] for r in records if r["group"] == g],
                                          [r["rating"] for r in records if r["group"] == g])} for o in grid[g]] for g in GROUPS},
        "per_image": [{"name": r["name"], "rating": r["rating"], "in_sample": a, "leave_one_out": b}
                      for r, a, b in zip(records, in_sample, loo)],
    }


def decide(results: dict[str, dict], resolution_limit: float, reference: str = "v1") -> dict:
    """Apply the change rule. Returns the winner (the reference if nothing passes) and each candidate's gain."""
    ref = results[reference]["leave_one_out"]["mae"]
    gains = {name: ref - r["leave_one_out"]["mae"] for name, r in results.items() if name != reference}
    passing = [n for n, g in gains.items() if g > resolution_limit]
    winner = min(passing, key=lambda n: results[n]["leave_one_out"]["mae"]) if passing else reference  # min keeps the first on ties
    return {"reference": reference, "reference_loo_mae": ref, "gains": gains, "passing": passing, "winner": winner,
            "changed": winner != reference}


def _opt(o: dict | None) -> str:
    return "-" if o is None else f"{o['threshold']:g}" + ("" if o["halo"] else " no halo")


def format_report(results: dict, decision: dict, n: int, limit: float, commit: str) -> str:
    verdict = (f"method changes to candidate {decision['winner']}" if decision["changed"]
               else "no candidate passes; phase3-method-v1 is kept")
    lines = [f"# Pre-gold round 2 on the tuning set ({date.today().isoformat()})", "",
             f"Commit at run time: `{commit}`. Generated by `python -m src.severity.pregold_round2`.", "",
             f"{n} tuning images, input B. Every choice a candidate makes is repeated inside each leave-one-out fold. "
             "MAE is in points against the single rater's tuning ratings.", "",
             f"**Change rule:** the method changes only if leave-one-out MAE improves on `v1` by more than {limit} points "
             "(the rating resolution limit).", "",
             "| candidate | chosen (rust / necrotic / mildew) | in-sample MAE (95% CI) | leave-one-out MAE (95% CI) | gain over v1 (leave-one-out) |",
             "|---|---|---|---|---:|"]
    for name, r in results.items():
        gain = "reference" if name == decision["reference"] else f"{decision['gains'][name]:+.2f}"
        lines.append(f"| {name} | {' / '.join(_opt(r['chosen'][g]) for g in GROUPS)} | "
                     f"{r['in_sample']['mae']:.2f} ({r['in_sample']['ci_low']:.2f}-{r['in_sample']['ci_high']:.2f}) | "
                     f"{r['leave_one_out']['mae']:.2f} ({r['leave_one_out']['ci_low']:.2f}-{r['leave_one_out']['ci_high']:.2f}) | {gain} |")
    lines += ["", f"**Decision: {verdict}.**", ""]
    for name, r in results.items():
        lines += [f"## Candidate {name}: MAE per option (in-sample, per group)", ""]
        for g in GROUPS:
            lines.append(f"- **{g}**: " + " | ".join(f"{_opt(o)}: {o['mae']:.2f}" for o in r["option_mae"][g]))
        lines.append("")
    names = list(results)
    lines += ["## Per image: severity % (in-sample / leave-one-out)", "",
              "| image | rating | " + " | ".join(names) + " |", "|---|---:|" + "---:|" * len(names)]
    for k, row in enumerate(results[names[0]]["per_image"]):
        cells = " | ".join(f"{results[c]['per_image'][k]['in_sample']:.1f} / {results[c]['per_image'][k]['leave_one_out']:.1f}" for c in names)
        lines.append(f"| `{row['name']}` | {row['rating']:.1f} | {cells} |")
    return "\n".join(lines) + "\n"


def main() -> None:
    import torch

    from src.models.inference import load_baseline
    from src.severity.sam2_model import load_sam2_predictor

    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--config", default="configs/config.yaml")
    parser.add_argument("--experiment", default="configs/experiments/phase3_round2.yaml")
    parser.add_argument("--debug", action="store_true", help="first 3 tuning images, outputs only in the experiment folder")
    args = parser.parse_args()
    config = load_config(args.config)
    experiment = yaml.safe_load(Path(args.experiment).read_text(encoding="utf-8"))
    grids = {name: options(c) for name, c in experiment["candidates"].items()}
    all_options = {g: list(dict.fromkeys(o for grid in grids.values() for o in grid[g])) for g in GROUPS}

    rows = tuning_rows(config)[:3] if args.debug else tuning_rows(config)
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    model = load_baseline(experiment["model"], experiment["checkpoint"], device)
    items = sp.load_inputs(rows, config, load_sam2_predictor(config), model, config["image"]["size"], device)
    records = make_records(items, all_options)
    results = {name: evaluate_candidate(records, grid, experiment["tune_on"]) for name, grid in grids.items()}
    decision = decide(results, experiment["resolution_limit"])

    exp_dir = create_experiment_dir("pregold_round2" + ("_debug" if args.debug else ""), args.config)
    shutil.copy(args.experiment, exp_dir / Path(args.experiment).name)
    (exp_dir / "metrics.json").write_text(json.dumps({"decision": decision, "candidates": results}, indent=2), encoding="utf-8")
    report = format_report(results, decision, len(records), experiment["resolution_limit"], get_git_commit_hash())
    out = exp_dir / TABLE.name if args.debug else TABLE
    out.write_text(report, encoding="utf-8")
    print(report)
    print(f"Wrote {out}; {exp_dir}")


if __name__ == "__main__":
    main()
